// Copies the scam word list from src/lib/scam.ts into worker/src/scam.js (run after editing the list).
import { readFileSync, writeFileSync } from 'node:fs';
const src = readFileSync(new URL('../src/lib/scam.ts', import.meta.url), 'utf8');
const list = src.match(/export const SCAM_WORDS: string\[\] = (\[[\s\S]*?\]);/)[1];
writeFileSync(new URL('../worker/src/scam.js', import.meta.url),
  `// GENERATED by scripts/sync-scam.mjs from src/lib/scam.ts - edit that file, then run: node scripts/sync-scam.mjs\nexport const SCAM_WORDS = ${list};\n`);
console.log('worker/src/scam.js updated');
